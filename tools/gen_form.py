HDR_DY={'ColFR':4,'EngFR':4}   # others: 2
_fr=[c[1] for c in C if c[0]=='Frame' and c[1]!='UnlockFR']
C2=[]
for (t,n,x,y,w,h,p,cap,g,ex) in C:
    if n in _fr:
        d=HDR_DY.get(n,2); y+=d; h-=d
    elif p in _fr:
        y-=HDR_DY.get(p,2)
    C2.append((t,n,x,y,w,h,p,cap,g,ex))
C=C2
T={'Frame':'Frame','Button':'Button','Label':'Label','CheckBox':'CheckBox','RadioButton':'RadioButton','TextBox':'TextBox','DropdownList':'DropdownList','PictureBox':'PictureBox','ProgressBar':'ProgressBar'}
